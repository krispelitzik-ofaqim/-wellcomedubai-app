type Ctx = { lang: Lang; setLang: (l: Lang) => void; toggle: () => void; t: (k: string) => string; isRTL: boolean };
const I18nCtx = createContext<Ctx>({ lang: 'he', setLang: () => {}, toggle: () => {}, t: (k) => k, isRTL: true });

// Detect the device/browser language on first launch → open in it if we support it, else English.
function detectDeviceLang(): Lang | null {
  try {
    let loc = '';
    if (typeof navigator !== 'undefined' && (navigator as any).language) loc = (navigator as any).language;
    else loc = Intl.DateTimeFormat().resolvedOptions().locale || '';
    const code = String(loc).toLowerCase().split('-')[0];
    const map: Record<string, Lang> = { he: 'he', iw: 'he', en: 'en', ru: 'ru', ar: 'ar', hi: 'hi' };
    return map[code] || null;
  } catch { return null; }
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');
  useEffect(() => {
    AsyncStorage.getItem('appLang').then(v => {
      if (v === 'en' || v === 'he' || v === 'ru' || v === 'hi' || v === 'ar') { setLangState(v); return; }
      const d = detectDeviceLang();          // first launch, no saved choice → follow the device language
      if (d) setLangState(d);
    }).catch(() => {});
  }, []);
  const setLang = (l: Lang) => { setLangState(l); AsyncStorage.setItem('appLang', l).catch(() => {}); };
  const toggle = () => setLang(lang === 'he' ? 'en' : lang === 'en' ? 'ru' : lang === 'ru' ? 'hi' : lang === 'hi' ? 'ar' : 'he');
  const t = (k: string) => {
    if (lang === 'ru') return RU[k] ?? STRINGS[k]?.en ?? STRINGS[k]?.he ?? k;
    if (lang === 'hi') return HI[k] ?? STRINGS[k]?.en ?? STRINGS[k]?.he ?? k;
    if (lang === 'ar') return AR[k] ?? STRINGS[k]?.en ?? STRINGS[k]?.he ?? k;
    return STRINGS[k]?.[lang] ?? STRINGS[k]?.he ?? k;
  };
  return <I18nCtx.Provider value={{ lang, setLang, toggle, t, isRTL: lang === 'he' || lang === 'ar' }}>{children}</I18nCtx.Provider>;
}

export const useI18n = () => useContext(I18nCtx);
